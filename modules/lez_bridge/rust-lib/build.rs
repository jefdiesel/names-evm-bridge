// The module builder puts the scaffold its lidl-gen generated at generated/provider_gen.rs before
// cargo runs. This copies it to OUT_DIR with its instance lock taken by try_lock
// (scaffold_patch.rs), and lib.rs includes that copy. The change is checked here (each site found
// exactly once, none left unchanged) and printed, so every build log shows the three sites; a
// generator that changed fails the build instead of building unpatched. Unit tests build without
// the scaffold: then nothing is generated and lib.rs includes nothing.

include!("scaffold_patch.rs");

/// The build's identity (`config().build`): `build-id.txt` beside Cargo.toml, written by
/// `modules/build-lgx.sh` (or the build host's script) before the module build, as
/// `commit=<short git commit>` and `built=<UTC date>` lines; else LEZ_BRIDGE_BUILD_COMMIT and
/// LEZ_BRIDGE_BUILD_DATE; else "unknown". Nix builds a copy of the source without `.git`, so git
/// is never asked here. A module build (the scaffold is there) refuses "unknown": every built
/// module can be told apart from every other (Names reads it after an update).
fn build_id(dir: &std::path::Path) -> (String, String) {
    println!("cargo:rerun-if-changed=build-id.txt");
    println!("cargo:rerun-if-env-changed=LEZ_BRIDGE_BUILD_COMMIT");
    println!("cargo:rerun-if-env-changed=LEZ_BRIDGE_BUILD_DATE");
    let file = std::fs::read_to_string(dir.join("build-id.txt")).unwrap_or_default();
    let field = |key: &str| file.lines().find_map(|l| l.trim().strip_prefix(key).map(|v| v.trim().to_owned())).filter(|v| !v.is_empty());
    let commit = field("commit=").or_else(|| std::env::var("LEZ_BRIDGE_BUILD_COMMIT").ok().filter(|v| !v.trim().is_empty())).unwrap_or_else(|| "unknown".to_owned());
    let built = field("built=").or_else(|| std::env::var("LEZ_BRIDGE_BUILD_DATE").ok().filter(|v| !v.trim().is_empty())).unwrap_or_else(|| "unknown".to_owned());
    let ok = |v: &str| v.chars().all(|c| c.is_ascii_alphanumeric() || "-:T._Z".contains(c)) && v.len() <= 40;
    if !ok(&commit) || !ok(&built) {
        panic!("lez_bridge build id: build-id.txt has a commit or date with unexpected characters");
    }
    (commit, built)
}

fn main() {
    let dir = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let (commit, built) = build_id(&dir);
    println!("cargo:rustc-env=LEZ_BRIDGE_BUILD_COMMIT={commit}");
    println!("cargo:rustc-env=LEZ_BRIDGE_BUILD_DATE={built}");
    let generated = dir.join("generated").join("provider_gen.rs");
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("provider_gen.rs");
    println!("cargo:rerun-if-changed=generated/provider_gen.rs");
    println!("cargo:rerun-if-changed=scaffold_patch.rs");
    println!("cargo:rerun-if-changed=build.rs");
    let text = match std::fs::read_to_string(&generated) {
        Ok(text) => text,
        Err(_) => {
            // Only unit tests build without it, and they don't include it; a module build that got
            // here without one stops at this line instead of building with no scaffold.
            std::fs::write(&out, "compile_error!(\"generated/provider_gen.rs is missing: the scaffold is generated by the module builder\");\n").unwrap();
            println!("cargo:rustc-env=LEZ_BRIDGE_SCAFFOLD_TRY_LOCK_SITES=none");
            return;
        }
    };
    if commit == "unknown" {
        panic!("lez_bridge build id: no commit for this module build. Build it with modules/build-lgx.sh (it writes rust-lib/build-id.txt from git), or write build-id.txt (commit=<short commit>, built=<UTC date>) before building.");
    }
    let patched = patch_scaffold(&text).unwrap_or_else(|why| panic!("lez_bridge scaffold patch: {why}"));
    for (number, line) in patched.lines().enumerate().filter(|(_, line)| line.contains("INSTANCE.0.try_lock()")) {
        println!("cargo:warning=lez_bridge scaffold patch: provider_gen.rs:{}: {}", number + 1, line.trim());
    }
    println!("cargo:rustc-env=LEZ_BRIDGE_SCAFFOLD_TRY_LOCK_SITES={}", patched.matches("INSTANCE.0.try_lock()").count());
    std::fs::write(&out, patched).unwrap();
}
